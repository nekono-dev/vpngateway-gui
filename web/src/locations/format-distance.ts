// 責務: 距離（km）の表示文字列を作る。1,000 km 単位の値を小数点以下第一位で表し、「k km」を付ける（例: 2102.7 → "2.1k km"）。

/**
 * 目的: 距離（km）を表示用の文字列にする。
 * 入力: km（距離。小数点以下第一位へ丸め済みでなくてもよい）。
 * 出力: 千 km 単位の値（小数点以下第一位）に「k km」を付けた文字列。例: 396.4 → "0.4k km"、2102.7 → "2.1k km"。
 */
export function formatDistance(km: number): string {
  return `${(km / 1000).toFixed(1)}k km`;
}
